"""Resolve public wheels once, then write an exact hash lock for this platform."""

import hashlib
import json
import os
import platform
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    manifest = json.loads((ROOT / "framework.lock.json").read_text(encoding="utf-8"))
    wheel = ROOT / manifest["wheel"]
    if hashlib.sha256(wheel.read_bytes()).hexdigest() != manifest["wheel_sha256"]:
        raise SystemExit("Framework wheel hash mismatch")
    report_path = ROOT / ".build" / "resolution.json"
    environment = dict(os.environ, TEMP=str(ROOT / ".build" / "tmp"), TMP=str(ROOT / ".build" / "tmp"))
    subprocess.run([
        sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
        "--only-binary=:all:", "--disable-pip-version-check", "--index-url", "https://pypi.org/simple",
        "--report", str(report_path), str(wheel), "httpx==0.28.1", "openai==2.46.0",
        "pytest==9.1.1", "ruff==0.16.1", "setuptools==84.0.0", "wheel==0.48.0",
    ], check=True, cwd=ROOT, env=environment)
    report = json.loads(report_path.read_text(encoding="utf-8"))
    lines = ["# Generated by scripts/lock_dependencies.py; install with --require-hashes.",
             f"# Platform: {sys.platform}; CPython {platform.python_version()}; {platform.machine()}.",
             "# Local framework wheel is independently fingerprinted in framework.lock.json."]
    records = []
    build_lines = ["# Bootstrap build tools; generated alongside requirements.lock."]
    for entry in sorted(report["install"], key=lambda entry: entry["metadata"]["name"].lower()):
        name, version = entry["metadata"]["name"], entry["metadata"]["version"]
        download = entry["download_info"]
        digest = download["archive_info"]["hashes"]["sha256"]
        if name.lower().replace("_", "-") == "ai-agent":
            if digest != manifest["wheel_sha256"]:
                raise SystemExit("Resolver selected a different framework wheel")
            requirement = "./" + manifest["wheel"]
        else:
            if urlsplit(download["url"]).hostname != "files.pythonhosted.org":
                raise SystemExit("Unexpected external package source")
            requirement = f"{name}=={version}"
        lines.append(f"{requirement} --hash=sha256:{digest}")
        if name.lower() in {"setuptools", "wheel", "packaging"}:
            build_lines.append(lines[-1])
        records.append({"name": name, "version": version, "sha256": digest})
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "requirements-build.lock").write_text("\n".join(build_lines) + "\n", encoding="utf-8")
    print(f"Wrote requirements.lock with {len(records)} exact package hashes")


if __name__ == "__main__":
    main()
